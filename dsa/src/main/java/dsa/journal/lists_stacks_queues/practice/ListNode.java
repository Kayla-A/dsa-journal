package dsa.journal.lists_stacks_queues.practice;

public class ListNode {
    int val;
    ListNode next;
    
    public ListNode(int val) {
        this.val = val;
    } // ListNode

    public int getVal() {
        return val;
    } // getVal

    public void setVal(int val) {
        this.val = val;
    } // setVal

    public ListNode getNext() {
        return next;
    } // getNext

    public void setNext(ListNode next) {
        this.next = next;
    } // setNext

    
} // ListNode
